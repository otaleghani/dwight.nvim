-- Feature-scoped task context
--------------------------------------------------------------------

--- Build detailed context for features referenced in a task description.
--- Unlike build_project_context() which gives a summary of ALL features,
--- this provides full file signatures and source snippets for the
--- specific feature(s) the task is working on.
--- Returns XML string or nil.
function M.build_feature_context(text)
  if not text then return nil end

  local features_ok, features = pcall(require, "dwight.features")
  if not features_ok then return nil end

  -- Find all feature names referenced in the text
  local referenced = {}
  local seen = {}

  -- Match $feature-name patterns
  for name in text:gmatch("%$([%w_%-%.]+)") do
    if not seen[name] then
      seen[name] = true
      referenced[#referenced + 1] = name
    end
  end

  -- Also match "feature X" patterns
  for name in text:gmatch("@feature:([%w_%-%.]+)") do
    if not seen[name] then
      seen[name] = true
      referenced[#referenced + 1] = name
    end
  end

  if #referenced == 0 then return nil end

  local parts = {}
  local total_chars = 0
  local MAX_CHARS = 15000

  for _, name in ipairs(referenced) do
    if total_chars >= MAX_CHARS then break end

    local feature = features.build_feature(name)
    if feature then
      -- Use the full XML format which includes signatures
      local xml = features.format_xml(feature)
      if xml then
        parts[#parts + 1] = xml
        total_chars = total_chars + #xml
      end

      -- Also include source snippets (first 2KB of each file)
      local cwd = vim.fn.getcwd()
      for _, file in ipairs(feature.files) do
        if total_chars >= MAX_CHARS then break end
        local full = file.path:sub(1, 1) == "/" and file.path
          or (cwd .. "/" .. file.path)
        local f = io.open(full, "r")
        if f then
          local content = f:read("*a")
          f:close()
          if content and #content > 0 then
            if #content > 2000 then
              content = content:sub(1, 2000) .. "\n... (truncated)"
            end
            parts[#parts + 1] = string.format(
              '<feature_source path="%s">\n%s\n</feature_source>',
              file.path, content)
            total_chars = total_chars + #content
          end
        end
      end
    end
  end

  if #parts == 0 then return nil end
  return "<feature_context hint=\"Detailed context for features this task modifies. "
    .. "Use exact function signatures and types from here.\">\n"
    .. table.concat(parts, "\n")
    .. "\n</feature_context>"
end

