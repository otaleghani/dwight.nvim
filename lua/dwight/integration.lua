-- dwight/integration.lua
-- Connects Dwight's feature ecosystem into the agentic pipeline.
--
-- This module provides the glue between standalone Dwight features
-- (skills, pragmas, libs, features, commit, etc.) and the agentic
-- execution loop (auto.lua / agentic.lua).
--
-- Responsibilities:
--   build_skills_context()  — skills → XML context for agent prompts
--   build_libs_context()    — libs → XML context for agent prompts
--   pragma_sync(feature)    — propagate @feature: pragmas to new files
--   rebuild_features()      — rebuild feature index after file changes

local M = {}

local api = vim.api

--------------------------------------------------------------------
-- Skills context: inject project-local coding conventions
--------------------------------------------------------------------

--- Build XML context block from all project-local skills.
--- Skills are markdown files in .dwight/skills/ that encode
--- coding conventions, API patterns, and project-specific rules.
--- Returns nil if no skills found or project not initialized.
function M.build_skills_context()
  local ok, skills = pcall(require, "dwight.skills")
  if not ok then return nil end

  local skill_list = skills.list()
  if #skill_list == 0 then return nil end

  local parts = {}
  parts[#parts + 1] = "<skills hint=\"Project-local coding guidelines. Follow these conventions.\">"

  local total_chars = 0
  local MAX_CHARS = 8000  -- Cap total skill content

  for _, skill in ipairs(skill_list) do
    if total_chars >= MAX_CHARS then
      parts[#parts + 1] = "  <!-- ... more skills truncated -->"
      break
    end

    local content = skills.read(skill.name)
    if content and content ~= "" then
      -- Trim individual skills to 2K each
      if #content > 2000 then
        content = content:sub(1, 2000) .. "\n... (truncated)"
      end
      parts[#parts + 1] = string.format('  <skill name="%s">', skill.name)
      parts[#parts + 1] = content
      parts[#parts + 1] = "  </skill>"
      total_chars = total_chars + #content
    end
  end

  parts[#parts + 1] = "</skills>"
  return table.concat(parts, "\n")
end

--------------------------------------------------------------------
-- Libs context: inject library documentation
--------------------------------------------------------------------

--- Build XML context block from project-local library docs.
--- Libs are markdown files in .dwight/libs/ that document
--- dependencies and their APIs (generated by :DwightLib).
--- Returns nil if no libs found.
function M.build_libs_context()
  local ok, libs = pcall(require, "dwight.libs")
  if not ok then return nil end

  local lib_list = libs.list()
  if #lib_list == 0 then return nil end

  local parts = {}
  parts[#parts + 1] = "<libraries hint=\"Project dependency documentation. Use these APIs correctly.\">"

  local total_chars = 0
  local MAX_CHARS = 6000

  for _, lib_name in ipairs(lib_list) do
    if total_chars >= MAX_CHARS then
      parts[#parts + 1] = "  <!-- ... more libs truncated -->"
      break
    end

    local content = libs.read(lib_name)
    if content and content ~= "" then
      if #content > 2000 then
        content = content:sub(1, 2000) .. "\n... (truncated)"
      end
      parts[#parts + 1] = string.format('  <lib name="%s">', lib_name)
      parts[#parts + 1] = content
      parts[#parts + 1] = "  </lib>"
      total_chars = total_chars + #content
    end
  end

  parts[#parts + 1] = "</libraries>"
  return table.concat(parts, "\n")
end

--------------------------------------------------------------------
-- Pragma propagation: keep @feature: tags on new files
--------------------------------------------------------------------

--- Detect the feature name from a request/task description.
--- Returns the feature name (string) or nil.
function M.detect_feature_name(text)
  if not text then return nil end
  -- Match "$feature-name" or "@feature:feature-name" patterns
  return text:match("%$([%w_%-%.]+)")
    or text:match("@feature:([%w_%-%.]+)")
    or text:match("feature%s+([%w_%-%.]+)")
end

--- Detect the correct comment prefix for a file based on extension.
local function comment_prefix(filepath)
  local ext = filepath:match("%.([^.]+)$") or ""
  local map = {
    lua = "-- ", py = "# ", rb = "# ", sh = "# ", bash = "# ",
    go = "// ", rs = "// ", js = "// ", ts = "// ", tsx = "// ", jsx = "// ",
    java = "// ", c = "// ", cpp = "// ", h = "// ", hpp = "// ",
    css = "/* ", scss = "/* ", html = "<!-- ",
  }
  return map[ext]
end

--- Check if a file already has a @feature: pragma.
local function has_feature_pragma(filepath)
  local f = io.open(filepath, "r")
  if not f then return false end
  -- Only check first 10 lines (pragmas go at the top)
  for i = 1, 10 do
    local line = f:read("*l")
    if not line then break end
    if line:match("@feature:") then
      f:close()
      return true
    end
  end
  f:close()
  return false
end

--- Add a @feature: pragma to the top of a file.
--- Returns true if the pragma was added, false if skipped.
function M.add_pragma(filepath, feature_name)
  local prefix = comment_prefix(filepath)
  if not prefix then return false end  -- unknown file type

  if has_feature_pragma(filepath) then return false end  -- already tagged

  local f = io.open(filepath, "r")
  if not f then return false end
  local content = f:read("*a")
  f:close()

  -- Build pragma line
  local pragma_line = string.format("%s@feature:%s\n", prefix, feature_name)

  -- For HTML/CSS, need closing comment
  if prefix == "<!-- " then
    pragma_line = string.format("<!-- @feature:%s -->\n", feature_name)
  elseif prefix == "/* " then
    pragma_line = string.format("/* @feature:%s */\n", feature_name)
  end

  -- Write back with pragma prepended
  local out = io.open(filepath, "w")
  if not out then return false end
  out:write(pragma_line .. content)
  out:close()

  return true
end

--- Propagate @feature: pragmas to new files created during a task.
--- Looks at git diff to find new files, checks if they're near existing
--- feature files, and adds the pragma if missing.
---
--- feature_name: string|nil — if known, only propagate this feature.
---                            if nil, detect from directory proximity.
--- Returns { added = { "path1", "path2" }, skipped = N }
function M.pragma_sync(feature_name)
  local result = { added = {}, skipped = 0 }

  -- Get list of new files from git
  local cwd = vim.fn.getcwd()
  local new_files_raw = vim.fn.system("git diff --name-only HEAD~1..HEAD --diff-filter=A 2>/dev/null")
  if not new_files_raw or vim.trim(new_files_raw) == "" then
    return result
  end

  local new_files = vim.split(vim.trim(new_files_raw), "\n", { plain = true })
  if #new_files == 0 then return result end

  -- Build a map of directories → feature names from existing pragmas
  local dir_features = {}
  if not feature_name then
    pcall(function()
      local features = require("dwight.features")
      for _, name in ipairs(features.names()) do
        local feature = features.build_feature(name)
        if feature then
          for _, file in ipairs(feature.files) do
            local dir = file.path:match("^(.+)/[^/]+$")
            if dir then
              dir_features[dir] = name
            end
          end
        end
      end
    end)
  end

  -- Process each new file
  for _, rel_path in ipairs(new_files) do
    local full = cwd .. "/" .. rel_path

    -- Determine which feature this file belongs to
    local target_feature = feature_name
    if not target_feature then
      -- Check if the file is in a directory that belongs to a feature
      local dir = rel_path:match("^(.+)/[^/]+$")
      if dir then
        target_feature = dir_features[dir]
        -- Also check parent dir (for nested modules like skills/paths.lua)
        if not target_feature then
          local parent = dir:match("^(.+)/[^/]+$")
          if parent then target_feature = dir_features[parent] end
        end
      end
    end

    if target_feature then
      local added = M.add_pragma(full, target_feature)
      if added then
        result.added[#result.added + 1] = rel_path
      else
        result.skipped = result.skipped + 1
      end
    else
      result.skipped = result.skipped + 1
    end
  end

  return result
end

--------------------------------------------------------------------
-- Feature index rebuild
--------------------------------------------------------------------

--- Invalidate the feature cache so the next scan picks up new files.
--- Call after file creation/deletion.
function M.rebuild_features()
  pcall(function()
    local features = require("dwight.features")
    -- Features module rescans on each call, so we just need to
    -- notify the developer that the index has changed
    local names = features.names()
    if #names > 0 then
      pcall(function()
        require("dwight.session_log").append(
          string.format("🔄 Feature index rebuilt: %d features (%s)",
            #names, table.concat(names, ", ")))
      end)
    end
  end)
end

