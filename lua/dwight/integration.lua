-- Post-session analysis
--------------------------------------------------------------------

--- Run post-session analysis after a successful DwightAuto/DwightRefactor.
--- Checks for oversized features, stale docs, and audit suggestions.
--- Outputs directly to the status buffer.
function M.post_session(request, sessions, status)
  -- 1. Check for oversized features that may need splitting
  pcall(function()
    local split = require("dwight.split")
    local oversized = split.audit()
    if #oversized > 0 then
      status.append("")
      status.append("⚠️  Feature size warnings:")
      for _, r in ipairs(oversized) do
        local a = r.analysis
        status.append(string.format("  $%s — %s (%d files, %d lines)",
          r.name, r.reason, a.file_count, a.total_lines))
      end
      status.append("  → Run :DwightSplitFeature to split large features")
    end
  end)

  -- 2. Identify changed features and suggest audit
  local changed_features = {}
  pcall(function()
    -- Collect all files changed across sessions
    local changed_files = {}
    for _, s in ipairs(sessions or {}) do
      for _, f in ipairs(s.files_created or {}) do changed_files[f] = true end
      for _, f in ipairs(s.files_edited or {}) do changed_files[f] = true end
    end

    -- Also check git for changed files
    local diff_files = vim.fn.system("git diff --name-only HEAD~" .. #sessions .. "..HEAD 2>/dev/null")
    if diff_files then
      for f in diff_files:gmatch("[^\n]+") do changed_files[f] = true end
    end

    -- Map changed files to features
    local features = require("dwight.features")
    for _, name in ipairs(features.names()) do
      local feature = features.build_feature(name)
      if feature then
        for _, file in ipairs(feature.files) do
          if changed_files[file.path] then
            changed_features[name] = true
          end
        end
      end
    end
  end)

  local cf_list = {}
  for name in pairs(changed_features) do cf_list[#cf_list + 1] = "$" .. name end
  table.sort(cf_list)

  if #cf_list > 0 then
    status.append("")
    status.append("📋 Suggested follow-ups:")
    status.append(string.format("  Changed features: %s", table.concat(cf_list, ", ")))
    status.append("  → :DwightAudit <feature>  — check code quality")
    status.append("  → :DwightDevDocs          — update developer documentation")
  end

  -- 3. Suggest squash + smart commit
  local commit_count = #sessions
  if commit_count > 1 then
    status.append("")
    status.append(string.format(
      "💡 %d checkpoint commits were made. To clean up git history:",
      commit_count))
    status.append(string.format(
      "  → :DwightSquash           — squash into one commit with a smart message"))
  end

  -- 4. If solving a GitHub issue, offer PR
  pcall(function()
    local gh = require("dwight.github")
    if gh._active_issue then
      status.append("")
      status.append(string.format("🐙 Solving GitHub issue #%d — ready for PR:",
        gh._active_issue.number))
      status.append("  → :DwightPR               — push and create pull request")
    end
  end)
end

--------------------------------------------------------------------
-- Squash: combine dwight checkpoint commits into one
--------------------------------------------------------------------

--- Squash all dwight checkpoint commits since the last non-dwight commit
--- into a single commit with a smart message.
--- If callback is provided, generates an LLM commit message (async).
--- Otherwise uses a combined summary.
function M.squash()
  -- Find how many consecutive dwight commits there are
  local log_raw = vim.fn.system(
    "git log --oneline --format='%s' -50 2>/dev/null")
  if not log_raw or vim.trim(log_raw) == "" then
    vim.notify("[dwight] No git history found.", vim.log.levels.WARN)
    return
  end

  local count = 0
  for line in log_raw:gmatch("[^\n]+") do
    if line:match("^dwight") then
      count = count + 1
    else
      break
    end
  end

  if count <= 1 then
    vim.notify("[dwight] Only 1 dwight commit found — nothing to squash.", vim.log.levels.INFO)
    return
  end

  vim.notify(string.format("[dwight] Squashing %d dwight commits…", count), vim.log.levels.INFO)

  -- Collect the titles from the commits being squashed
  local titles_raw = vim.fn.system(
    string.format("git log --oneline --format='%%s' -%d 2>/dev/null", count))
  local titles = {}
  if titles_raw then
    for line in titles_raw:gmatch("[^\n]+") do
      -- Strip the "dwight(N/M): " or "dwight: " prefix
      local clean = line:gsub("^dwight%([%d/]+%): ", ""):gsub("^dwight: ", "")
      if clean ~= "" then titles[#titles + 1] = clean end
    end
  end

  -- Soft reset to before the dwight commits
  local reset_code = os.execute(
    string.format("cd %s && git reset --soft HEAD~%d 2>/dev/null",
      vim.fn.shellescape(vim.fn.getcwd()), count))
  if reset_code ~= 0 then
    vim.notify("[dwight] Git reset failed — cannot squash.", vim.log.levels.ERROR)
    return
  end

  -- Try to generate a smart message using DwightCommit's LLM flow
  local commit_ok, commit = pcall(require, "dwight.commit")
  if commit_ok and commit.generate then
    -- DwightCommit will see the staged diff and open an editor
    vim.notify(string.format(
      "[dwight] Squashed %d commits. Generating commit message…", count),
      vim.log.levels.INFO)
    commit.generate()
  else
    -- Fallback: commit with combined summary
    local msg = "dwight: " .. table.concat(titles, "; "):sub(1, 200)
    vim.fn.system(string.format(
      "cd %s && git commit -m %s --no-verify 2>/dev/null",
      vim.fn.shellescape(vim.fn.getcwd()),
      vim.fn.shellescape(msg)))
    vim.notify(string.format(
      "[dwight] ✅ Squashed %d commits into one.", count), vim.log.levels.INFO)
  end
end

return M
