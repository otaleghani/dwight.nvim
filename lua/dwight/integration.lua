--- Build the pragma instruction block for agent prompts.
--- Explains the @feature: pragma system and when to use it.
function M.pragma_instructions()
  local features_ok, features = pcall(require, "dwight.features")
  if not features_ok then return "" end

  local names = features.names()
  if #names == 0 then return "" end

  return string.format([[
## Feature Pragmas — IMPORTANT
This project uses `@feature:name` pragma comments to track which files belong to which feature.
Active features: %s

RULES:
- When you CREATE a new file that belongs to a feature, add a pragma comment on line 1.
  Format: `// @feature:feature-name Description of what this file does`
  (use the comment style for the file's language: `--` for Lua, `#` for Python, `//` for Go/JS/TS)
- When you SPLIT a file into multiple files, EVERY new file must get the pragma from the original.
  Example: splitting `skills.lua` (@feature:skills) into `skills/paths.lua`, `skills/picker.lua`
  → each new file gets `-- @feature:skills` on line 1.
- When you MOVE a file, the pragma moves with it (it's just a comment in the source).
- Do NOT remove existing pragmas. They are how the project tracks feature boundaries.
- The description after the feature name is optional but helpful.
]], table.concat(names, ", "))
end

--- Build the full integration context for an agent prompt.
--- Combines skills, libs, and pragma instructions.
function M.build_full_context()
  local parts = {}

  local skills_ctx = M.build_skills_context()
  if skills_ctx then parts[#parts + 1] = skills_ctx end

  local libs_ctx = M.build_libs_context()
  if libs_ctx then parts[#parts + 1] = libs_ctx end

  local pragma_inst = M.pragma_instructions()
  if pragma_inst ~= "" then parts[#parts + 1] = pragma_inst end

  if #parts == 0 then return nil end
  return table.concat(parts, "\n\n")
end

